// Builds api/_lib/recorded-data.js from the recorded Gemini answers in scripts/recorded/.
// Each review file: { "draft": "D-101", "recordedAt": "YYYY-MM-DD", "response": { ...the /api/review answer } }
// Each image file:  { "asset": "assets/x.png", "recordedAt": "YYYY-MM-DD", "response": { ...the /api/alt-text answer } }
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { seedWorkspace } from '../js/seed.js';
import { reviewRequestBody } from '../js/ai.js';
import { normalizeReviewBody } from '../api/review.js';
import { reviewKey } from '../api/_lib/recorded.js';

const dir = path.join(path.dirname(fileURLToPath(import.meta.url)), 'recorded');
const ws = seedWorkspace();
const reviews = {};
const images = {};
for (const name of fs.readdirSync(dir).filter((n) => n.endsWith('.json')).sort()) {
  const rec = JSON.parse(fs.readFileSync(path.join(dir, name), 'utf8'));
  const clean = { ...rec.response };
  delete clean.cached; delete clean.recorded; delete clean.warning;
  if (rec.draft) {
    const draft = ws.drafts.find((d) => d.id === rec.draft);
    const body = JSON.parse(JSON.stringify(reviewRequestBody(ws, draft, rec.recordedAt)));
    const n = normalizeReviewBody(body);
    reviews[reviewKey({ text: body.text, ...n })] = { draft: rec.draft, recordedAt: rec.recordedAt, response: clean };
  } else if (rec.asset) {
    images[rec.asset] = { recordedAt: rec.recordedAt, response: clean };
  }
}
const out = `// Generated by scripts/build-recorded.mjs from scripts/recorded/*.json. Do not edit by hand.\nexport const REVIEWS = ${JSON.stringify(reviews, null, 1)};\nexport const IMAGES = ${JSON.stringify(images, null, 1)};\n`;
fs.writeFileSync(path.join(dir, '..', '..', 'api', '_lib', 'recorded-data.js'), out);
console.log('reviews:', Object.values(reviews).map((r) => r.draft).join(', ') || 'none', '| images:', Object.keys(images).join(', ') || 'none');
